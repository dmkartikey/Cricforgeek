export const flagCode = (name: string) => FLAG[name.replace(/ Women$/, '')] ?? null;
export const flagUrl = (code: string) => `/flags/${code}.svg`;

// Up to two initials from the meaningful words: "Kolkata Knight Riders" → KK, "Surrey" → SU, "MI Cape Town" → MI.
export function monogram(name: string) {
  const words = name.replace(/ Women$/, '').replace(/\(.*?\)/g, '').split(/[\s&-]+/).filter((w) => w && !/^(the|and|of|cricket|club|cc)$/i.test(w));
  if (!words.length) return '?';
  if (/^[A-Z]{2,3}$/.test(words[0])) return words[0].slice(0, 2);
  return words.length === 1 ? words[0].slice(0, 2).toUpperCase() : (words[0][0] + words[1][0]).toUpperCase();
}

// A steady colour per team, picked from a short list that reads well with white text in both themes.
const HUES = ['#1F6E5A', '#2F5D8A', '#7A3E6C', '#8A4B23', '#3E5C2A', '#5B4A8B', '#7B2F3B', '#1E6A7A', '#6B5A1E', '#44546A'];
export function badgeColour(name: string) {
  let h = 0;
  for (const ch of name.replace(/ Women$/, '')) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return HUES[h % HUES.length];
}
